-- US000-11: a pré-guia vira uma entidade própria. A guia só é criada na emissão (US005-5).

-- Linhas da V10 eram só de teste (sem beneficiário nem procedimentos) e não servem mais.
DELETE FROM Pre_Guia;

ALTER TABLE Pre_Guia RENAME COLUMN Data_Decisao TO Data_Reprovacao;

ALTER TABLE Pre_Guia
    ADD COLUMN Benf_ID               VARCHAR(20) NOT NULL,
    ADD COLUMN Med_ID                INT         NOT NULL,
    ADD COLUMN Emissor_ID            INT,
    ADD COLUMN Data_Criacao          DATE        NOT NULL DEFAULT CURRENT_DATE,
    ADD COLUMN Data_Aprovacao_Medico TIMESTAMP,
    ADD COLUMN Data_Aprovacao_Chefe  TIMESTAMP,
    ADD COLUMN Guia_ID               INT,
    ADD CONSTRAINT fk_pre_guia_benef FOREIGN KEY (Benf_ID)
        REFERENCES Beneficiario (PrecCP) ON UPDATE CASCADE ON DELETE RESTRICT,
    ADD CONSTRAINT fk_pre_guia_medico FOREIGN KEY (Med_ID)
    REFERENCES Medico (ID) ON UPDATE CASCADE ON DELETE RESTRICT,
    ADD CONSTRAINT fk_pre_guia_emissor FOREIGN KEY (Emissor_ID)
    REFERENCES Analista (ID) ON UPDATE CASCADE ON DELETE RESTRICT,
    ADD CONSTRAINT fk_pre_guia_guia FOREIGN KEY (Guia_ID)
    REFERENCES Guia (ID) ON UPDATE CASCADE ON DELETE RESTRICT,
    ADD CONSTRAINT ck_pre_guia_status CHECK (Status IN
    ('PRE_GUIA', 'COM_PENDENCIAS', 'VALIDADA', 'APROVADA', 'REPROVADA', 'EMITIDA'));

CREATE TABLE Pre_Guia_Proc (
                               ID             INT         GENERATED BY DEFAULT AS IDENTITY,
                               Pre_Guia_ID    BIGINT      NOT NULL,
                               Proc_ID        INT         NOT NULL,
                               Ocs_ID         VARCHAR(14) NOT NULL,
                               Qtd_Autorizada INT         NOT NULL,
                               CONSTRAINT pk_pre_guia_proc PRIMARY KEY (ID),
                               CONSTRAINT fk_pgp_pre_guia FOREIGN KEY (Pre_Guia_ID)
                                   REFERENCES Pre_Guia (ID) ON UPDATE CASCADE ON DELETE CASCADE,
                               CONSTRAINT fk_pgp_procedimento FOREIGN KEY (Proc_ID)
                                   REFERENCES Procedimento (ID) ON UPDATE CASCADE ON DELETE RESTRICT,
                               CONSTRAINT fk_pgp_ocs FOREIGN KEY (Ocs_ID)
                                   REFERENCES Ocs (CNPJ) ON UPDATE CASCADE ON DELETE RESTRICT
);

-- Guia: Data_Emissao substitui Data; aprovações e motivo agora ficam na Pre_Guia.
UPDATE Guia SET Data_Emissao = Data WHERE Data_Emissao IS NULL;

ALTER TABLE Guia
DROP COLUMN Data,
    DROP COLUMN Motivo_Reprovacao,
    DROP COLUMN Data_Aprovacao_Medico,
    DROP COLUMN Data_Aprovacao_Chefe,
    ALTER COLUMN Data_Emissao SET NOT NULL;